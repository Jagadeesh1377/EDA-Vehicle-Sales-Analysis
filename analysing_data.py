import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
df=pd.read_csv("/content/preprocessed_data.csv")
df

df.info()

"""Univaiate Analysis

1.Count plot
"""

count=sns.countplot(data=df,x="Brand")
for c in count.containers:
  plt.bar_label(c,padding=2)
  plt.xticks(rotation=30)

"""2.Pie Chart"""

fuel_type_count=df["Fuel_Type"].value_counts()
plt.pie(fuel_type_count.values,labels=fuel_type_count.index,autopct="%1.2f&&")
plt.legend()
plt.show()

"""3.Bar Chart"""

owner_count=df["Owner"].value_counts()
plt.bar(owner_count.index,owner_count.values)
plt.xlabel("Owners")
plt.ylabel("Count")
plt.show()

"""4.Histogram"""

plt.hist(df['Driven_KMs'], bins=10, edgecolor='black')
plt.xlabel("Driven KMs")
plt.ylabel("Frequency")
plt.show()

"""5.Box Plot"""

sns.boxplot(y=df['Selling_Price'])
plt.ylabel("Selling Price")
plt.show()

"""6.Histplot"""

sns.histplot(df['Mileage_kmpl'], bins=10, kde=True)
plt.xlabel("Mileage (kmpl)")
plt.ylabel("Count")
plt.show()

"""7.Violin Plot"""

sns.violinplot(y=df['Engine_CC'])
plt.ylabel("Engine CC")
plt.show()

"""Bivariate Analysis

1.Scatter Plot
"""

sns.scatterplot(x=df['Present_Price'],y=df['Selling_Price'])
plt.xlabel("Present Price")
plt.ylabel("Selling Price")
plt.show()

"""2.Grouped Count Plot"""

sns.countplot(x='Fuel_Type',hue='Transmission',data=df)
plt.xlabel("Fuel Type")
plt.ylabel("Count")
plt.show()

"""3.Stacked Bar Chart"""

data = pd.crosstab(df['Fuel_Type'], df['Transmission'])
data.plot(kind='bar', stacked=True)
plt.xlabel("Fuel Type")
plt.ylabel("Count")
plt.show()

"""Multivariate Analysis

1.Pair Plot
"""

sns.pairplot(df[['Selling_Price', 'Present_Price','Driven_KMs', 'Mileage_kmpl']])
plt.show()

"""2.Heat Maps"""

data = df.select_dtypes(include='number')
sns.heatmap(data.corr(), annot=True, cmap='coolwarm')
plt.show()

"""3.Joint Plot with hue"""

sns.jointplot(data=df,x='Present_Price',y='Selling_Price',hue='Fuel_Type')
plt.show()

"""4.Bubble Chart"""

plt.scatter(df['Present_Price'],df['Selling_Price'],s=df['Driven_KMs'] / 100,alpha=0.5)
plt.xlabel("Present Price")
plt.ylabel("Selling Price")
plt.show()

"""5.Scatter Plot with hue and size"""

sns.scatterplot(data=df,x='Present_Price',y='Selling_Price',hue='Fuel_Type',size='Driven_KMs',sizes=(20, 200))
plt.show()

